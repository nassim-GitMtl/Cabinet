#!/bin/sh
# Installs (or restarts) the clinic server. Safe to run again.
# Offline install: put cabinet-images.tar.gz (from export-images.sh) next to this script.
set -eu
cd "$(dirname "$0")"

command -v docker >/dev/null || { echo "Docker est requis (Docker Desktop ou Docker Engine)."; exit 1; }

if [ ! -f .env ]; then
  rand() { openssl rand -hex 24 2>/dev/null || head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n'; }
  ip=$( (ipconfig getifaddr en0 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}') || true)
  printf "Adresse du serveur sur le réseau du cabinet [%s] : " "${ip:-192.168.1.10}"
  read -r host || true
  host=${host:-${ip:-192.168.1.10}}
  cat > .env <<ENV
# Generated by install.sh on $(date). Keep this file private and backed up.
CLINIC_HOST=$host
DB_OWNER_PASSWORD=$(rand)
DB_APP_PASSWORD=$(rand)
DB_SYNC_PASSWORD=$(rand)
MFA_ENCRYPTION_KEY=$(rand)$(rand)
AUTH_RATE_LIMIT_SECRET=$(rand)$(rand)
TZ=Africa/Algiers
BACKUP_HOUR=21
BACKUP_KEEP_DAYS=30
BACKUP_DIR=./backups
HTTPS_PORT=443
HTTP_PORT=80
CABINET_SYNC_WORKER=on
ENV
  chmod 600 .env
  echo "Fichier .env créé (secrets générés)."
fi
# A rerun over an installation created before clinic/cloud sync must remain
# safe: add only the new secret and preserve every existing value.
if ! grep -q '^DB_SYNC_PASSWORD=' .env; then
  sync_secret=$(openssl rand -hex 24 2>/dev/null || head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')
  printf '\nDB_SYNC_PASSWORD=%s\n' "$sync_secret" >> .env
  chmod 600 .env
fi
mkdir -p backups

if [ -f cabinet-images.tar.gz ]; then
  echo "Chargement des images hors ligne…"
  gunzip -c cabinet-images.tar.gz | docker load
else
  echo "Construction des images (nécessite internet la première fois)…"
  docker compose build
fi

docker compose up -d --wait db app proxy backup
. ./.env
echo
echo "Cabinet Dentaire Pro est prêt :  https://$CLINIC_HOST"
echo "Certificat à installer sur chaque appareil :  http://$CLINIC_HOST/ca.crt"
echo "Sauvegardes quotidiennes à ${BACKUP_HOUR}h dans : $(pwd)/backups"
